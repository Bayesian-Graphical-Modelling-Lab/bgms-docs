# Companion scripts for the Examples series.
#
# Every page in examples/ ships a plain R script that reruns its analysis. The
# scripts are generated from the pages with knitr::purl(), never hand-written:
# edit the page, and the next render rewrites the script. That is the whole
# convention, and it is what keeps a downloaded script from drifting away from
# the page a reader is looking at.
#
# This runs as the project `pre-render` step (see _quarto.yml), so the scripts
# published beside the pages always match them. purl() parses a .qmd, it never
# evaluates a chunk, so this step needs neither bgms nor the baked fixtures.
#
# Usage (from the repo root), to regenerate them by hand:
#   Rscript scripts/extract-example-code.R
#
# Which chunks reach the script:
#
#   * Reader-facing chunks do, including the `eval: false` mirrors. Those
#     mirrors are the calls the page tells you to make, so the script must run
#     them for real. knitr::purl() comments out `eval: false` code, so the
#     option is stripped from a working copy of the page before tangling.
#   * Chunks marked `purl: false` do not. Put that on the machinery a page
#     needs but a reader does not: the fixture loader, hidden refits, anything
#     that exists only to make the rendered page render.
#
# File names carry the page's position in the series; see
# scripts/examples-series.R, which owns the order.

project_dir = Sys.getenv("QUARTO_PROJECT_DIR", unset = ".")
source(file.path(project_dir, "scripts", "examples-series.R"))

pages_dir = file.path(project_dir, "examples")
out_dir = file.path(pages_dir, "R")

if(!dir.exists(pages_dir)) {
  cat("example scripts: no examples/ directory, nothing to extract\n")
  quit(save = "no")
}
dir.create(out_dir, showWarnings = FALSE, recursive = TRUE)

# Tangle from a working copy with `eval: false` dropped, so the mirrored calls
# arrive as runnable code rather than as comments.
runnable_copy = function(path) {
  lines = readLines(path, warn = FALSE)
  tmp = tempfile(fileext = ".qmd")
  writeLines(lines[!grepl("^#\\|\\s*eval:\\s*false\\s*$", lines)], tmp)
  tmp
}

trim_blanks = function(x) {
  blank = !nzchar(trimws(x))
  x = x[!(blank & c(FALSE, head(blank, -1)))]  # collapse runs to one
  blank = !nzchar(trimws(x))
  if(length(x) > 0 && blank[1]) x = x[-1]
  if(length(x) > 0 && blank[length(blank)]) x = x[-length(x)]
  x
}

written = character(0)
for(slug in series_pages(project_dir)) {
  page = file.path("examples", paste0(slug, ".qmd"))
  dest = file.path(out_dir, sprintf("%s-%s.R", series_number(slug), slug))

  tmp = runnable_copy(file.path(project_dir, page))
  tangled = knitr::purl(tmp, output = tempfile(fileext = ".R"),
                        documentation = 0L, quiet = TRUE)
  unlink(tmp)

  header = c(
    sprintf("# Companion script: %s", slug),
    sprintf("# Generated from %s by scripts/extract-example-code.R.", page),
    "# Do not edit this file; edit the page and re-render.",
    ""
  )
  writeLines(c(header, trim_blanks(readLines(tangled, warn = FALSE))), dest)
  unlink(tangled)
  written = c(written, basename(dest))
}

# A script whose page is gone would still be published as a download.
stale = setdiff(list.files(out_dir, pattern = "[.]R$"), written)
if(length(stale) > 0) unlink(file.path(out_dir, stale))

cat(sprintf("example scripts: wrote %d companion script%s\n",
            length(written), if(length(written) == 1L) "" else "s"))
if(length(written) > 0) cat("  ", paste(written, collapse = ", "), "\n")
